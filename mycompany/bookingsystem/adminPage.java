    private void tblMTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblMTableMouseClicked
        // TODO add your handling code here:
        DefaultTableModel model = (DefaultTableModel)tblMTable.getModel();
        int row = tblMTable.getSelectedRow();
        
        txtMFilm.setText(model.getValueAt(row,0).toString());
        String genre1 = model.getValueAt(row, 1).toString();
        switch (genre1) {
            case "Action":
                cmbMGenre.setSelectedIndex(0);
                break;
            case "Adventure":
                cmbMGenre.setSelectedIndex(1);
                break;
            case "Comedy":
                cmbMGenre.setSelectedIndex(2);
                break;
            case "Drama":
                cmbMGenre.setSelectedIndex(3);
                break;   
            case "Fantasy":
                cmbMGenre.setSelectedIndex(4);
                break;
            case "Horror":
                cmbMGenre.setSelectedIndex(5);
                break;
            case "LGBTQ+":
                cmbMGenre.setSelectedIndex(6);
                break;
            case "Mystery":
                cmbMGenre.setSelectedIndex(7);
                break;
            case "Romance":
                cmbMGenre.setSelectedIndex(8);
                break;
            case "Science Fiction":
                cmbMGenre.setSelectedIndex(9);
                break;
        }
        
        String cin = model.getValueAt(row, 2).toString();
        switch (cin) {
            case "Cineplex1":
                cmbMCinema.setSelectedIndex(0);
                break;
            case "Cineplex2":
                cmbMCinema.setSelectedIndex(1);
                break;
            case "Cineplex3":
                cmbMCinema.setSelectedIndex(2);
                break;
            case "Cineplex4":
                cmbMCinema.setSelectedIndex(3);
                break;   
            case "Cineplex5":
                cmbMCinema.setSelectedIndex(4);
                break;
        }
        
        String scr = model.getValueAt(row, 3).toString();
        switch (scr) {
            case "1":
                cmbMScreen.setSelectedIndex(0);
                break;
            case "2":
                cmbMScreen.setSelectedIndex(1);
                break;
            case "3":
                cmbMScreen.setSelectedIndex(2);
                break;
            case "4":
                cmbMScreen.setSelectedIndex(3);
                break;   
            case "5":
                cmbMScreen.setSelectedIndex(4);
                break;
        }
        
        txtMDate.setText(model.getValueAt(row,4).toString());
        String tim = model.getValueAt(row, 5).toString();
        switch (tim) {
            case "10:00 AM":
                cmbMTime.setSelectedIndex(0);
                break;
            case "12:00 PM":
                cmbMTime.setSelectedIndex(1);
                break;
            case "2:00 PM":
                cmbMTime.setSelectedIndex(2);
                break;
            case "4:00 PM":
                cmbMTime.setSelectedIndex(3);
                break;   
            case "6:00 PM":
                cmbMTime.setSelectedIndex(4);
                break;
            case "8:00 PM":
                cmbMTime.setSelectedIndex(4);
                break;
              
        }
        String stat = model.getValueAt(row, 6).toString();
        switch (stat) {
            case "Now Showing":
                cmbMStatus.setSelectedIndex(0);
                break;
            case "Coming Soon":
                cmbMStatus.setSelectedIndex(1);
                break;
        }
        
    }//GEN-LAST:event_tblMTableMouseClicked

