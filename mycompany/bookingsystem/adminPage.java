    private void btnMDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMDeleteActionPerformed
        // TODO add your handling code here:
          int confirm = JOptionPane.showConfirmDialog(null,"Do you want to delete this record?","Delete Record",JOptionPane.YES_NO_OPTION,JOptionPane.QUESTION_MESSAGE);
        if(confirm == JOptionPane.YES_OPTION){
        DefaultTableModel model = (DefaultTableModel)tblMTable.getModel();
        int selectedRecord = tblMTable.getSelectedRow();
        
        model.removeRow(selectedRecord);
        JOptionPane.showMessageDialog(null, "DELETE SUCCESSFULLY!", "RECORD DELETE", JOptionPane.INFORMATION_MESSAGE);
        }
        else{
            JOptionPane.showMessageDialog(null, "DELETE NOT SUCCESSFUL", "RECORD DELETE", JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_btnMDeleteActionPerformed

